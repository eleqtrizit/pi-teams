/**
 * Automatic worker reports.
 *
 * When a worker's run settles, the extension sends the worker's final reply to
 * the team-lead. These helpers hold the pure logic: pull the final reply out
 * of a run's messages and shape the report that goes to the lead.
 */

/** Subject line prefix of every automatic report. */
export const REPORT_SUBJECT_PREFIX = "Report from";

/** Report body sent when a run ends without any assistant text. */
export const EMPTY_REPORT_TEXT = "The run finished without a text reply.";

/** Report body sent when the run was aborted before it finished. */
export const ABORTED_REPORT_TEXT = "The run was interrupted before it finished.";

/** A report ready to send to the team-lead. */
export interface WorkerReport {
  subject: string;
  text: string;
}

/** Minimal shape of an agent message that this module reads. */
interface MessageLike {
  role?: unknown;
  content?: unknown;
}

/**
 * Join the text blocks of one assistant message.
 *
 * @param content - The message content: a string or a list of content blocks
 * @returns The trimmed text, or an empty string when the message has no text
 */
function textOf(content: unknown): string {
  if (typeof content === "string") return content.trim();
  if (!Array.isArray(content)) return "";
  return content
    .filter(
      (block): block is { type: "text"; text: string } =>
        typeof block === "object" &&
        block !== null &&
        (block as { type?: unknown }).type === "text" &&
        typeof (block as { text?: unknown }).text === "string",
    )
    .map((block) => block.text.trim())
    .filter((text) => text.length > 0)
    .join("\n");
}

/**
 * Extract the worker's final reply from the messages of one run.
 *
 * Walks backwards and returns the text of the newest assistant message that
 * has any. Assistant messages that only contain tool calls are skipped.
 *
 * @param messages - Messages generated by the run, oldest first
 * @returns The final reply text, or null when no assistant message has text
 */
export function extractFinalReply(messages: readonly unknown[]): string | null {
  for (let i = messages.length - 1; i >= 0; i--) {
    const message = messages[i] as MessageLike | null;
    if (!message || message.role !== "assistant") continue;
    const text = textOf(message.content);
    if (text) return text;
  }
  return null;
}

/** Most replies one report carries. Older replies are dropped first. */
export const MAX_REPORT_REPLIES = 20;

/** Heading between replies when a report carries more than one. */
const REPLY_SEPARATOR = "\n\n---\n\n";

/**
 * Add a reply to the replies collected during one settle cycle.
 *
 * A settle cycle can hold several runs, for example when a teammate message
 * starts a second run before the first run's report is sent. Each run adds
 * its final reply. A run without text adds nothing.
 *
 * @param replies - Replies collected so far, oldest first
 * @param reply - The newest run's final reply, or null when it had none
 * @returns The updated list, capped at MAX_REPORT_REPLIES entries
 */
export function appendReply(replies: readonly string[], reply: string | null): string[] {
  if (reply === null) return [...replies];
  return [...replies, reply].slice(-MAX_REPORT_REPLIES);
}

/**
 * Join the replies of one settle cycle into the report body.
 *
 * @param replies - Replies in the order the runs produced them
 * @returns The single reply unchanged, or numbered replies when there are several, or null when empty
 */
function joinReplies(replies: readonly string[]): string | null {
  if (replies.length === 0) return null;
  if (replies.length === 1) return replies[0];
  return replies.map((reply, index) => `Reply ${index + 1} of ${replies.length}:\n\n${reply}`).join(REPLY_SEPARATOR);
}

/**
 * Build the report a worker sends to the team-lead after its run settles.
 *
 * @param agentName - Name of the reporting worker
 * @param replies - The final replies of every run in the settle cycle, oldest first
 * @param aborted - True when the run was aborted, for example with Escape
 * @returns The subject and body of the report
 */
export function buildWorkerReport(
  agentName: string,
  replies: readonly string[],
  aborted: boolean,
): WorkerReport {
  const subject = `${REPORT_SUBJECT_PREFIX} ${agentName}`;
  const body = joinReplies(replies);
  if (aborted) {
    const partial = body ? `\n\nReplies before the interruption:\n\n${body}` : "";
    return { subject, text: `${ABORTED_REPORT_TEXT}${partial}` };
  }
  return { subject, text: body ?? EMPTY_REPORT_TEXT };
}

/** Note appended to the report of a worker that closed itself. */
export const CLOSED_REPORT_NOTE = "This agent closed itself after these replies and is no longer running.";

/**
 * Build the report a worker sends to the team-lead just before it closes itself.
 *
 * A closing worker never reaches its settle event, so the extension sends this
 * report from the `close_myself` tool instead.
 *
 * @param agentName - Name of the closing worker
 * @param replies - The worker's replies so far, oldest first
 * @returns The subject and body of the report
 */
export function buildClosingReport(agentName: string, replies: readonly string[]): WorkerReport {
  const { subject, text } = buildWorkerReport(agentName, replies, false);
  const body = replies.length === 0 ? "" : `${text}\n\n`;
  return { subject, text: `${body}${CLOSED_REPORT_NOTE}` };
}
